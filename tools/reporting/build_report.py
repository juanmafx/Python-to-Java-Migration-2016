import json
import platform
import subprocess
import sys
import xml.etree.ElementTree as ElementTree
from datetime import UTC, datetime
from pathlib import Path


def read_suites(paths: list[Path]) -> list[dict[str, str]]:
    results = []
    for path in paths:
        for case in ElementTree.parse(path).getroot().iter("testcase"):
            outcome = "passed"
            if case.find("failure") is not None or case.find("error") is not None:
                outcome = "failed"
            elif case.find("skipped") is not None:
                outcome = "skipped"
            results.append({"name": f"{case.get('classname')}.{case.get('name')}", "outcome": outcome})
    return sorted(results, key=lambda result: result["name"])


def tally(results: list[dict[str, str]]) -> dict[str, int]:
    counts = {"total": len(results), "passed": 0, "failed": 0, "skipped": 0}
    for result in results:
        counts[result["outcome"]] += 1
    return counts


def tool_version(command: list[str]) -> str:
    completed = subprocess.run(command, capture_output=True, text=True, check=True)
    return (completed.stdout or completed.stderr).splitlines()[0].strip()


def render_markdown(report: dict) -> str:
    lines = [
        "# Test Report",
        "",
        f"Generated by `scripts/run-tests.sh` on {report['generated_at']} from base commit `{report['base_commit']}`.",
        "",
        f"- Python: {report['environment']['python']}",
        f"- Java: {report['environment']['java']}",
        "",
        "| Suite | Total | Passed | Failed | Skipped |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for name in ("python", "java"):
        counts = report["suites"][name]["counts"]
        lines.append(f"| {name} | {counts['total']} | {counts['passed']} | {counts['failed']} | {counts['skipped']} |")
    differential = report["differential"]
    lines += [
        "",
        f"Differential run: seed {differential['seed']}, {differential['cases']} cases, "
        f"{differential['mismatches']} mismatches.",
        "",
        "Per-test outcomes are in `test-report.json`.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    build, destination = Path(sys.argv[1]), Path(sys.argv[2])
    python_results = read_suites([build / "pytest.xml"])
    java_results = read_suites(sorted(Path("java/target/surefire-reports").glob("TEST-*.xml")))
    differential = json.loads((build / "differential.json").read_text(encoding="utf-8"))
    report = {
        "generated_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "base_commit": tool_version(["git", "rev-parse", "--short", "HEAD"]),
        "environment": {
            "python": platform.python_version(),
            "java": tool_version(["java", "-version"]),
        },
        "suites": {
            "python": {"counts": tally(python_results), "tests": python_results},
            "java": {"counts": tally(java_results), "tests": java_results},
        },
        "differential": differential,
    }
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "test-report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    (destination / "TEST_REPORT.md").write_text(render_markdown(report), encoding="utf-8")
    failed = tally(python_results)["failed"] + tally(java_results)["failed"]
    return 1 if failed or differential["mismatches"] else 0


if __name__ == "__main__":
    sys.exit(main())
